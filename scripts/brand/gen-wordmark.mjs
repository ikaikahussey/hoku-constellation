/**
 * Generates components/brand/wordmark-paths.ts — "HOKU Insider" as SVG path outlines.
 *
 * Helvetica Neue is not web-licensed and not redistributable, so the outlines are produced from a
 * bold Helvetica-metric sans available on the build machine. Preference order:
 *   1. $WORDMARK_FONT (path to Helvetica Neue Bold / Neue Haas Grotesk Bold .otf/.ttf if licensed)
 *   2. Liberation Sans Bold (metric-compatible with Arial/Helvetica; open licence)
 *   3. DejaVu Sans Bold
 *
 * Usage: node scripts/brand/gen-wordmark.mjs
 */
import { existsSync, writeFileSync } from 'node:fs'
import opentype from 'opentype.js'
import { readFileSync } from 'node:fs'

const CANDIDATES = [
  process.env.WORDMARK_FONT,
  '/System/Library/Fonts/HelveticaNeue.ttc',
  '/usr/share/fonts/truetype/liberation/LiberationSans-Bold.ttf',
  '/usr/share/fonts/truetype/liberation2/LiberationSans-Bold.ttf',
  '/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf',
].filter(Boolean)

const fontPath = CANDIDATES.find(p => existsSync(p))
if (!fontPath) { console.error('No suitable bold sans font found'); process.exit(1) }
const fontBytes = readFileSync(fontPath)
const font = opentype.parse(fontBytes.buffer.slice(fontBytes.byteOffset, fontBytes.byteOffset + fontBytes.byteLength))

const SIZE = 100 // px per em
const TRACKING = -0.01 * SIZE // slight negative tracking, matching headline style
const text = 'HOKU Insider'

// Lay out glyph by glyph so we can apply tracking and tighten the word space.
let x = 0
const paths = []
const glyphs = font.stringToGlyphs(text)
const baseline = SIZE * (font.ascender / font.unitsPerEm)
for (let i = 0; i < glyphs.length; i++) {
  const g = glyphs[i]
  const p = g.getPath(x, baseline, SIZE)
  const d = p.toPathData(2)
  if (d) paths.push(d)
  let adv = (g.advanceWidth / font.unitsPerEm) * SIZE
  if (text[i] === ' ') adv *= 0.85
  if (i + 1 < glyphs.length) adv += font.getKerningValue(g, glyphs[i + 1]) / font.unitsPerEm * SIZE
  x += adv + TRACKING
}
const width = Math.ceil(x - TRACKING)
const height = Math.ceil(SIZE * ((font.ascender - font.descender) / font.unitsPerEm))
const viewBox = `0 0 ${width} ${height}`

const ts = `// Generated by scripts/brand/gen-wordmark.mjs from ${fontPath.split('/').pop()} — do not edit by hand.
export const WORDMARK_VIEWBOX = '${viewBox}'
export const WORDMARK_PATHS: string[] = [
${paths.map(p => `  '${p}',`).join('\n')}
]
`
writeFileSync(new URL('../../components/brand/wordmark-paths.ts', import.meta.url), ts)
console.log(`wrote components/brand/wordmark-paths.ts from ${fontPath} (${viewBox})`)
